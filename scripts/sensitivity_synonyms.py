"""Sensitivity analysis: synonym-expanded literature search.

The published (primary) numbers search Europe PMC by the accepted GBIF binomial
only. This script re-runs the evidence step with every taxon searched under its
accepted name OR the curators' names OR all GBIF backbone synonyms
(``PALIMPSEST_SYNONYMS=1``), then re-runs the same modern-evidence models and
lead ranking (same controls, seeds and code) and compares the two.

Primary outputs are never touched; everything goes to

* ``data/processed/sensitivity_synonyms/`` (evidence_pairs, taxon_info, pairs_scored ...)
* ``results/sensitivity_synonyms/``        (stats.json, leads.csv, tables/, figures/, summary.md)

Usage (from the repo root, ``PYTHONPATH=src``)::

    python scripts/sensitivity_synonyms.py evidence   # ~13k cached Europe PMC POST queries
    python scripts/sensitivity_synonyms.py analyze    # models + leads on the new counts
    python scripts/sensitivity_synonyms.py summary    # summary.md, primary vs synonyms
    python scripts/sensitivity_synonyms.py all
"""
from __future__ import annotations

import json
import os
import shutil
import sys
import time

import pandas as pd

from palimpsest.paths import PROCESSED, RESULTS, TABLES

SENS_PROCESSED = PROCESSED / "sensitivity_synonyms"
SENS_RESULTS = RESULTS / "sensitivity_synonyms"


def step_evidence() -> None:
    os.environ["PALIMPSEST_SYNONYMS"] = "1"
    from palimpsest.evidence import run_evidence
    from palimpsest.sources import http

    print(run_evidence(out_processed=SENS_PROCESSED, out_results=SENS_RESULTS))
    print("http:", http.stats)


def step_analyze() -> None:
    from palimpsest.analysis.run import run_analysis

    s = run_analysis(evidence_dir=SENS_PROCESSED, out_processed=SENS_PROCESSED, out_results=SENS_RESULTS)
    shutil.copyfile(SENS_RESULTS / "tables" / "leads.csv", SENS_RESULTS / "leads.csv")
    print("leads:", s["n_leads"])


# ---------------------------------------------------------------------------
# comparison
# ---------------------------------------------------------------------------
LABEL = {"both": "Persistent (both)", "dsc_only": "Dioscorides only", "cul_only": "Culpeper only",
         "unclaimed": "Unclaimed (all controls)"}


def _by(rows, key="term"):
    return {r[key]: r for r in rows}


def _ci(r, k):
    return f"{r[k]:.2f} [{r['ci'][0]:.2f}–{r['ci'][1]:.2f}]"


def _p(x):
    return f"{x:.1g}" if x < 0.001 else f"{x:.3f}"


def step_summary() -> str:
    P = json.loads((RESULTS / "stats.json").read_text(encoding="utf-8"))["modern"]
    S = json.loads((SENS_RESULTS / "stats.json").read_text(encoding="utf-8"))["modern"]
    lines = ["# Sensitivity analysis: synonym-expanded literature search", "",
             "Primary = accepted GBIF binomial only (published numbers, `results/stats.json`). "
             "Synonyms = accepted name OR curated names OR all GBIF backbone synonyms "
             "(`PALIMPSEST_SYNONYMS=1`, Europe PMC searchPOST). Same claims, same 12 seeded "
             "controls per plant, same models and lead rules. Generated by "
             "`scripts/sensitivity_synonyms.py`.", ""]

    # --- literature volume
    pe = pd.read_csv(PROCESSED / "evidence_pairs.csv")
    se = pd.read_csv(SENS_PROCESSED / "evidence_pairs.csv")
    pt = pe.drop_duplicates("taxon").set_index("taxon").taxon_total
    st = se.drop_duplicates("taxon").set_index("taxon").taxon_total
    ti = pd.read_csv(SENS_PROCESSED / "taxon_info.csv")
    nnames = ti.search_names.fillna("").str.split("; ").str.len()
    m = pe.merge(se, on=["taxon", "concept_id"], suffixes=("_p", "_s"))
    assert len(m) == len(pe) == len(se), "pair plans differ"
    lines += ["## Literature found", "",
              "| | Primary | Synonyms |", "|---|---|---|",
              f"| Plants searched | {len(pt)} | {len(st)} |",
              f"| Search names per plant (median / max) | 1 / 1 | {int(nnames.median())} / {int(nnames.max())} |",
              f"| Plants with ≥ 1 paper | {int((pt > 0).sum())} | {int((st > 0).sum())} |",
              f"| Papers per plant (median) | {int(pt.median())} | {int(st.median())} |",
              f"| Total plant papers (sum over plants) | {int(pt.sum()):,} | {int(st.sum()):,} |",
              f"| Pairs with ≥ 1 co-mentioning paper | {int((m.pair_p > 0).sum()):,} / {len(m):,} | "
              f"{int((m.pair_s > 0).sum()):,} / {len(m):,} |",
              f"| Plants whose paper count rose ≥ 2× | – | {int(((st + 1) / (pt.reindex(st.index) + 1) >= 2).sum())} |",
              ""]
    gain = (st - pt.reindex(st.index)).sort_values(ascending=False).head(8)
    lines += ["Largest gains: " + "; ".join(f"*{t}* {int(pt[t]):,} → {int(st[t]):,}" for t in gain.index), ""]

    # --- groups
    gp, gs = _by(P["groups"], "group"), _by(S["groups"], "group")
    lines += ["## Share of pairs with ≥ 1 co-mentioning paper", "",
              "| Group | n pairs | Primary: claimed vs matched controls | Synonyms: claimed vs matched controls |",
              "|---|---|---|---|"]
    for g in ("both", "dsc_only", "cul_only", "unclaimed"):
        a, b = gp[g], gs[g]
        if g == "unclaimed":
            lines.append(f"| {LABEL[g]} | {a['n_pairs']:,} | {a['share_any_paper']:.0%} | {b['share_any_paper']:.0%} |")
        else:
            lines.append(f"| {LABEL[g]} | {a['n_pairs']:,} | {a['share_any_paper']:.0%} vs "
                         f"{a['matched_unclaimed_share']:.0%} | {b['share_any_paper']:.0%} vs "
                         f"{b['matched_unclaimed_share']:.0%} |")
    lines.append("")

    # --- models
    lp, ls = _by(P["logit_fixed_effects"]), _by(S["logit_fixed_effects"])
    pp, ps = _by(P["poisson_rate_ratios"]), _by(S["poisson_rate_ratios"])
    qp, qs = _by(P["poisson_given_studied"]), _by(S["poisson_given_studied"])
    cp, cs = _by(P["conditional_logit"]), _by(S["conditional_logit"])
    lines += ["## Models (claimed vs unclaimed, cluster-robust 95% CI)", "",
              "| Estimate | Group | Primary | Synonyms |", "|---|---|---|---|"]
    for g in ("both", "dsc_only", "cul_only"):
        lines.append(f"| Logit OR, indication FE + plant volume | {LABEL[g]} | {_ci(lp[g], 'odds_ratio')}, "
                     f"p = {_p(lp[g]['p'])} | {_ci(ls[g], 'odds_ratio')}, p = {_p(ls[g]['p'])} |")
    for g in ("both", "dsc_only", "cul_only"):
        lines.append(f"| Poisson RR, indication FE + offset | {LABEL[g]} | {_ci(pp[g], 'rate_ratio')} | "
                     f"{_ci(ps[g], 'rate_ratio')} |")
    for g in ("both", "dsc_only", "cul_only"):
        lines.append(f"| Poisson RR given studied (pair ≥ 1) | {LABEL[g]} | {_ci(qp[g], 'rate_ratio')}, "
                     f"p = {_p(qp[g]['p'])} | {_ci(qs[g], 'rate_ratio')}, p = {_p(qs[g]['p'])} |")
    lines.append(f"| Conditional logit OR | {LABEL['both']} | {cp['both']['odds_ratio']:.2f} | "
                 f"{cs['both']['odds_ratio']:.2f} |")
    wp, ws = P["wilcoxon_within_taxon"], S["wilcoxon_within_taxon"]
    lines.append(f"| Within-plant Wilcoxon (log2 lift) | claimed vs unclaimed | p = {_p(wp['p_value'])} "
                 f"(n = {wp['n_taxa']}) | p = {_p(ws['p_value'])} (n = {ws['n_taxa']}) |")
    lines.append(f"| Plants tested / without literature | | {P['n_taxa_tested']} / "
                 f"{P['n_taxa_without_literature']} | {S['n_taxa_tested']} / {S['n_taxa_without_literature']} |")
    lines.append("")

    # --- leads
    lp_ = pd.read_csv(TABLES / "leads.csv")
    ls_ = pd.read_csv(SENS_RESULTS / "leads.csv")
    la_s = pd.read_csv(SENS_RESULTS / "tables" / "leads_all.csv")
    la_p = pd.read_csv(TABLES / "leads_all.csv")
    key = lambda d: set(zip(d.taxon, d.concept_id))
    sm = m.set_index(["taxon", "concept_id"])
    dropped = lp_[[k not in key(la_s) for k in zip(lp_.taxon, lp_.concept_id)]].copy()
    dropped["pair_syn"] = [int(sm.loc[(t, c), "pair_s"]) for t, c in zip(dropped.taxon, dropped.concept_id)]
    out_top = lp_[[k not in key(ls_) for k in zip(lp_.taxon, lp_.concept_id)]]
    new_top = ls_[[k not in key(lp_) for k in zip(ls_.taxon, ls_.concept_id)]]
    lines += ["## Leads", "",
              f"* Candidates (persistent pairs with ≤ 4 papers): primary {len(la_p)}, synonyms {len(la_s)}.",
              f"* Of the {len(lp_)} published top leads, **{len(dropped)} drop out of the candidate pool** "
              "because synonym searches reveal more than 4 co-mentioning papers; "
              f"{len(out_top) - len(dropped)} more remain candidates but leave the top {len(ls_)} "
              f"(re-ranking); {len(lp_) - len(out_top)} stay in the top {len(ls_)}.",
              f"* Top 8 published leads still in the synonym top {len(ls_)}: "
              f"{sum(k in key(ls_) for k in zip(lp_.head(8).taxon, lp_.head(8).concept_id))} of 8; "
              f"still candidates: {sum(k in key(la_s) for k in zip(lp_.head(8).taxon, lp_.head(8).concept_id))} of 8.",
              ""]
    if len(dropped):
        lines += ["Published leads that drop out (papers: primary → synonyms):", "",
                  "| Rank | Plant | Indication | Papers |", "|---|---|---|---|"]
        for r in dropped.sort_values("rank").itertuples():
            lines.append(f"| {r.rank} | *{r.taxon}* | {r.label} | {int(r.pair)} → {r.pair_syn} |")
        lines.append("")
    pool_out = la_p[[k not in key(la_s) for k in zip(la_p.taxon, la_p.concept_id)]].copy()
    pool_out["pair_syn"] = [int(sm.loc[(t, c), "pair_s"]) for t, c in zip(pool_out.taxon, pool_out.concept_id)]
    if len(pool_out):
        lines += [f"Lead candidates (full ranking) that drop out because synonyms reveal > 4 papers "
                  f"({len(pool_out)}; none was in the published top {len(lp_)}): "
                  + "; ".join(f"*{r.taxon}* – {r.label} ({int(r.pair)} → {r.pair_syn})"
                              for r in pool_out.itertuples()), ""]
    lines += [f"Published top-{len(lp_)} leads displaced by re-ranking: "
              + "; ".join(f"{r.rank}. *{r.taxon}* – {r.label}" for r in out_top.itertuples()),
              f"New entries in the synonym top {len(ls_)}: "
              + "; ".join(f"{r.rank}. *{r.taxon}* – {r.label} ({int(r.pair)})" for r in new_top.itertuples()),
              "", "Synonym top 8: " + "; ".join(f"{r.rank}. *{r.taxon}* – {r.label} ({int(r.pair)})"
                                                for r in ls_.head(8).itertuples()), ""]
    ros = m[m.taxon == "Salvia rosmarinus"]
    if len(ros):
        sc = pd.read_csv(SENS_PROCESSED / "pairs_scored.csv").set_index(["taxon", "concept_id"]).group
        ros = ros.assign(group=[sc[(t, c)] for t, c in zip(ros.taxon, ros.concept_id)])
        cl = ros[ros.group != "unclaimed"].sort_values("pair_s", ascending=False)
        lines += ["**Rosemary** (*Salvia rosmarinus*, searched also as *Rosmarinus officinalis* …): "
                  f"{int(pt['Salvia rosmarinus'])} → {int(st['Salvia rosmarinus'])} papers. Claimed pairs gain "
                  "most where Culpeper alone made the claim ("
                  + ", ".join(f"{c} {int(a)} → {int(b_)}" for c, a, b_ in
                              zip(cl.concept_id.head(4), cl.pair_p.head(4), cl.pair_s.head(4)))
                  + "). Its only persistent pair ("
                  + ", ".join(f"{c}: {int(a)} → {int(b_)} papers" for c, a, b_ in
                              zip(cl[cl.group == 'both'].concept_id, cl[cl.group == 'both'].pair_p,
                                  cl[cl.group == 'both'].pair_s))
                  + ") stays unstudied, and with the larger plant volume it becomes a *stronger* lead "
                  f"(synonym rank {', '.join(str(r) for r in ls_[ls_.taxon == 'Salvia rosmarinus']['rank']) or '–'}).",
                  ""]
    both_p = pd.read_csv(PROCESSED / "pairs_scored.csv")
    both_keys = set(zip(both_p[both_p.group == "both"].taxon, both_p[both_p.group == "both"].concept_id))
    mb = m[[k in both_keys for k in zip(m.taxon, m.concept_id)]]
    lines += [f"Persistent pairs with 0 papers under the accepted name: {int((mb.pair_p == 0).sum())}; "
              f"of these, {int(((mb.pair_p == 0) & (mb.pair_s > 0)).sum())} gain ≥ 1 paper with synonyms.", ""]
    txt = "\n".join(lines)
    (SENS_RESULTS / "summary.md").write_text(txt, encoding="utf-8")
    return txt


def main(argv: list[str]) -> None:
    steps = argv or ["all"]
    if "all" in steps:
        steps = ["evidence", "analyze", "summary"]
    for s in steps:
        t0 = time.time()
        if s == "evidence":
            step_evidence()
        elif s == "analyze":
            step_analyze()
        elif s == "summary":
            print(step_summary())
        else:
            raise SystemExit(f"unknown step {s}")
        print(f"[{s}] done in {time.time() - t0:.1f}s", flush=True)


if __name__ == "__main__":
    main(sys.argv[1:])
